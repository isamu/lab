/**
 * 行頭の箇条の印。Markdown の印（- * + と 1. 1)）は後ろに空白が要る。「・」は日本語で手で打つ箇条の印で、空白を置かずに続けて書く。
 * 「**賃料**」の太字や「-5」は印ではない。
 */
const LIST_MARKER = /^([ \t]*)(?:(?:[-*+]|\d{1,9}[.)])[ \t]+|・[ \t\u3000]*)/gmu;

/** 行頭で項目の名だけを包む太字（「**賃料**：」）。名の後ろにすぐ区切りが来るときだけで、文の中の太字は外さない。 */
const BOLD_LABEL = /^([ \t]*)\*\*([^*:：|｜\n]+)\*\*(?=[ \t]*[|｜:：])/gmu;

/**
 * 内容から種類を選ぶ行を読むために、行頭の箇条の印と、項目の名を包む太字を外す。字下げは残す。
 * 「- 賃料：85,000円」「・賃料：85,000円」「**賃料**：85,000円」も「賃料：85,000円」と同じ項目の行として数えるため。
 */
export const withoutListMarkers = (source: string): string => source.replace(LIST_MARKER, "$1").replace(BOLD_LABEL, "$1$2");
